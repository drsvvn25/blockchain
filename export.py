"""
export.py
---------
Saves simulation results to JSON and CSV files in the current folder.

Analogy: The print button.  It does no thinking; it writes what it is
handed into files named with the current time.

Every exported JSON includes simulation_only: True so nobody mistakes
the data for a real blockchain record.
"""

import csv
import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional


# ---------------------------------------------------------------------------
# ExportEngine
# ---------------------------------------------------------------------------

class ExportEngine:
    """
    Writes simulation outputs to JSON and CSV files.

    Usage
    -----
    >>> exp = ExportEngine(output_dir=".")
    >>> path = exp.export_results_json(config, results)
    """

    DISCLAIMER = (
        "SIMULATION ONLY. This data was generated by SegmentChain, a Python "
        "simulator.  No real network, real transactions, or real nodes are involved."
    )

    def __init__(self, output_dir: str = ".") -> None:
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _timestamp(self) -> str:
        return datetime.now().strftime("%Y%m%d_%H%M%S")

    def _path(self, name: str, ext: str) -> str:
        fname = f"{name}_{self._timestamp()}.{ext}"
        return os.path.join(self.output_dir, fname)

    def _wrap_json(self, payload: Any) -> dict:
        return {
            "export_time": datetime.now().isoformat(),
            "simulation_only": True,
            "disclaimer": self.DISCLAIMER,
            "data": payload,
        }

    def _write_json(self, path: str, data: dict) -> str:
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        return path

    def _write_csv(self, path: str, rows: List[dict]) -> str:
        if not rows:
            with open(path, "w", encoding="utf-8") as f:
                f.write("No data\n")
            return path
        with open(path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=rows[0].keys())
            writer.writeheader()
            writer.writerows(rows)
        return path

    # ------------------------------------------------------------------
    # Export methods
    # ------------------------------------------------------------------

    def export_results_json(
        self,
        config: dict,
        results: dict,
        filename: Optional[str] = None,
    ) -> str:
        """
        Write a scenario JSON: configuration + results.
        File name: segmentchain_experiment_<time>.json
        """
        path = filename or self._path("segmentchain_experiment", "json")
        payload = {"configuration": config, "results": results}
        return self._write_json(path, self._wrap_json(payload))

    def export_node_assignment_csv(
        self,
        rows: List[dict],
        filename: Optional[str] = None,
    ) -> str:
        """
        One row per (node, segment) pair.
        File name: segmentchain_node_assignment_<time>.csv
        """
        path = filename or self._path("segmentchain_node_assignment", "csv")
        return self._write_csv(path, rows)

    def export_storage_metrics_csv(
        self,
        rows: List[dict],
        filename: Optional[str] = None,
    ) -> str:
        """
        Per-node byte counts.
        File name: segmentchain_storage_metrics_<time>.csv
        """
        path = filename or self._path("segmentchain_storage_metrics", "csv")
        return self._write_csv(path, rows)

    def export_segment_summary_csv(
        self,
        rows: List[dict],
        filename: Optional[str] = None,
    ) -> str:
        """
        Segment table (id, start_height, end_height, block_count).
        File name: segmentchain_segment_summary_<time>.csv
        """
        path = filename or self._path("segmentchain_segment_summary", "csv")
        return self._write_csv(path, rows)

    def export_availability_results_csv(
        self,
        rows: List[dict],
        filename: Optional[str] = None,
    ) -> str:
        """
        Availability summary + per-segment survivors + failed nodes.
        File name: segmentchain_availability_<time>.csv
        """
        path = filename or self._path("segmentchain_availability", "csv")
        return self._write_csv(path, rows)

    def create_experiment_report(
        self,
        config: dict,
        storage: dict,
        availability_results: List[dict],
        probability_results: dict,
        filename: Optional[str] = None,
    ) -> str:
        """
        Full JSON report combining all results.
        File name: segmentchain_report_<time>.json
        """
        path = filename or self._path("segmentchain_report", "json")
        payload = {
            "configuration": config,
            "storage": storage,
            "availability": availability_results,
            "probability": probability_results,
        }
        return self._write_json(path, self._wrap_json(payload))

    # ------------------------------------------------------------------
    # Generic writer (used internally and directly)
    # ------------------------------------------------------------------

    def export_table_csv(
        self,
        rows: List[dict],
        base_name: str = "segmentchain_table",
        filename: Optional[str] = None,
    ) -> str:
        """
        Generic CSV writer.  Headers come from the first row's keys.
        Empty data writes a 'No data' note.
        """
        path = filename or self._path(base_name, "csv")
        return self._write_csv(path, rows)

    def __repr__(self) -> str:
        return f"ExportEngine(output_dir={self.output_dir!r})"
